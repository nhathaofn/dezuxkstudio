package main

import (
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strings"
	"time"

	"app/internal/contracts"
)

var (
	rawMessageType = reflect.TypeFor[json.RawMessage]()
	timeType       = reflect.TypeFor[time.Time]()
	emptyType      = reflect.TypeFor[contracts.Empty]()
)

type generator struct {
	enums   map[reflect.Type]string
	structs map[string]reflect.Type
	pending []reflect.Type
}

// Generate renders the TypeScript module.
func Generate() ([]byte, error) {
	g := &generator{enums: map[reflect.Type]string{}, structs: map[string]reflect.Type{}}
	for _, e := range contracts.Enums() {
		g.enums[e.GoType] = e.Name
	}

	var b strings.Builder
	b.WriteString("// Code generated by cmd/contractgen from internal/contracts. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: go run ./cmd/contractgen\n\n")
	fmt.Fprintf(&b, "export const PROTOCOL_VERSION = %q;\n", contracts.ProtocolVersion)
	fmt.Fprintf(&b, "export const AUTH_SUBPROTOCOL_PREFIX = %q;\n\n", contracts.AuthSubprotocolPrefix)

	// Enums
	for _, e := range contracts.Enums() {
		fmt.Fprintf(&b, "export const %sValues = [%s] as const;\n", e.Name, quoteAll(e.Values))
		fmt.Fprintf(&b, "export type %s = (typeof %sValues)[number];\n\n", e.Name, e.Name)
	}

	// Collect every struct reachable from the catalogue (and the wire protocol).
	roots := []reflect.Type{
		reflect.TypeFor[contracts.ClientMessage](),
		reflect.TypeFor[contracts.ResponseMessage](),
		reflect.TypeFor[contracts.EventMessage](),
		reflect.TypeFor[contracts.ErrorBody](),
	}
	for _, a := range contracts.Actions() {
		roots = append(roots, a.Payload, a.Result)
	}
	for _, e := range append(contracts.Events(), contracts.NativeEvents()...) {
		roots = append(roots, e.Data)
	}
	for _, m := range contracts.Bridge() {
		roots = append(roots, m.Params...)
		if m.Result != nil {
			roots = append(roots, m.Result)
		}
	}
	for _, r := range roots {
		if _, err := g.tsType(r); err != nil {
			return nil, err
		}
	}

	// Emit structs sorted by name for stable output.
	names := make([]string, 0, len(g.structs))
	for n := range g.structs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		decl, err := g.declare(n, g.structs[n])
		if err != nil {
			return nil, err
		}
		b.WriteString(decl)
	}

	// Actions
	b.WriteString("export const Actions = {\n")
	for _, a := range contracts.Actions() {
		fmt.Fprintf(&b, "  /** %s */\n  %s: %q,\n", a.Summary, constKey(a.Name), a.Name)
	}
	b.WriteString("} as const;\nexport type ActionName = (typeof Actions)[keyof typeof Actions];\n\n")
	b.WriteString("export interface ActionMap {\n")
	for _, a := range contracts.Actions() {
		p, _ := g.tsType(a.Payload)
		r, _ := g.tsType(a.Result)
		fmt.Fprintf(&b, "  %q: { payload: %s; result: %s };\n", a.Name, p, r)
	}
	b.WriteString("}\n\n")

	writeEvents(&b, g, "Events", "EventName", "EventMap", contracts.Events())
	writeEvents(&b, g, "NativeEvents", "NativeEventName", "NativeEventMap", contracts.NativeEvents())

	// Bridge
	b.WriteString("/** Methods bound by the desktop shell (window.go.desktop.Bridge). */\n")
	b.WriteString("export interface BridgeApi {\n")
	for _, m := range contracts.Bridge() {
		params := make([]string, len(m.Params))
		for i, p := range m.Params {
			t, _ := g.tsType(p)
			params[i] = fmt.Sprintf("arg%d: %s", i+1, t)
		}
		result := "void"
		if m.Result != nil {
			result, _ = g.tsType(m.Result)
		}
		fmt.Fprintf(&b, "  /** %s */\n  %s(%s): Promise<%s>;\n", m.Summary, m.Name, strings.Join(params, ", "), result)
	}
	b.WriteString("}\n")

	return []byte(b.String()), nil
}

func writeEvents(b *strings.Builder, g *generator, constName, typeName, mapName string, specs []contracts.EventSpec) {
	fmt.Fprintf(b, "export const %s = {\n", constName)
	for _, e := range specs {
		fmt.Fprintf(b, "  /** %s */\n  %s: %q,\n", e.Summary, constKey(e.Name), e.Name)
	}
	fmt.Fprintf(b, "} as const;\nexport type %s = (typeof %s)[keyof typeof %s];\n\n", typeName, constName, constName)
	fmt.Fprintf(b, "export interface %s {\n", mapName)
	for _, e := range specs {
		d, _ := g.tsType(e.Data)
		fmt.Fprintf(b, "  %q: %s;\n", e.Name, d)
	}
	b.WriteString("}\n\n")
}

// tsType maps a Go type to a TypeScript type expression, registering named structs.
func (g *generator) tsType(t reflect.Type) (string, error) {
	if name, ok := g.enums[t]; ok {
		return name, nil
	}
	switch t {
	case rawMessageType:
		return "unknown", nil
	case timeType:
		return "string", nil
	}
	switch t.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Pointer:
		inner, err := g.tsType(t.Elem())
		return inner + " | null", err
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string", nil
		}
		inner, err := g.tsType(t.Elem())
		if strings.Contains(inner, "|") {
			inner = "(" + inner + ")"
		}
		return inner + "[]", err
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map key must be string: %s", t)
		}
		inner, err := g.tsType(t.Elem())
		return "Record<string, " + inner + ">", err
	case reflect.Struct:
		if t.Name() == "" {
			return "", fmt.Errorf("anonymous structs are not supported: %s", t)
		}
		if prev, ok := g.structs[t.Name()]; ok {
			if prev != t {
				return "", fmt.Errorf("type name collision: %s and %s", prev, t)
			}
			return t.Name(), nil
		}
		g.structs[t.Name()] = t
		for _, f := range fieldsOf(t) {
			if _, err := g.tsType(f.Type); err != nil {
				return "", err
			}
		}
		return t.Name(), nil
	}
	return "", fmt.Errorf("unsupported type %s", t)
}

func (g *generator) declare(name string, t reflect.Type) (string, error) {
	if t == emptyType {
		return "export type Empty = Record<string, never>;\n\n", nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "export interface %s {\n", name)
	for _, f := range fieldsOf(t) {
		jsonName, omitempty := jsonTag(f)
		ft := f.Type
		optional := omitempty
		if omitempty && ft.Kind() == reflect.Pointer {
			ft = ft.Elem()
		}
		ts, err := g.tsType(ft)
		if err != nil {
			return "", err
		}
		opt := ""
		if optional {
			opt = "?"
		}
		fmt.Fprintf(&b, "  %s%s: %s;\n", jsonName, opt, ts)
	}
	b.WriteString("}\n\n")
	return b.String(), nil
}

// fieldsOf returns serialised fields, flattening embedded structs like encoding/json.
func fieldsOf(t reflect.Type) []reflect.StructField {
	var out []reflect.StructField
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		if name, _ := jsonTag(f); name == "-" {
			continue
		}
		if f.Anonymous && f.Type.Kind() == reflect.Struct && f.Tag.Get("json") == "" {
			out = append(out, fieldsOf(f.Type)...)
			continue
		}
		out = append(out, f)
	}
	return out
}

func jsonTag(f reflect.StructField) (name string, omitempty bool) {
	tag := f.Tag.Get("json")
	if tag == "" {
		return f.Name, false
	}
	parts := strings.Split(tag, ",")
	name = parts[0]
	if name == "" {
		name = f.Name
	}
	for _, p := range parts[1:] {
		if p == "omitempty" || p == "omitzero" {
			omitempty = true
		}
	}
	return name, omitempty
}

func constKey(name string) string {
	return strings.ToUpper(strings.NewReplacer(":", "_", ".", "_", "-", "_").Replace(name))
}

func quoteAll(vs []string) string {
	q := make([]string, len(vs))
	for i, v := range vs {
		q[i] = fmt.Sprintf("%q", v)
	}
	return strings.Join(q, ", ")
}
