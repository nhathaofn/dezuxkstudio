// ProcessBatch processes a slice of BatchItems concurrently using a thread-safe worker pool.
// Output ordering is guaranteed to match the input slice index.
func (e *Engine) ProcessBatch(ctx context.Context, items []BatchItem, workers int) []BatchResult {
	return e.ProcessBatchProgress(ctx, items, workers, nil)
}

// ProcessBatchProgress is ProcessBatch that calls onDone(done, total) after each item (from any
// worker goroutine; calls are serialised). Callers use it to report progress on long batches.
func (e *Engine) ProcessBatchProgress(ctx context.Context, items []BatchItem, workers int, onDone func(done, total int)) []BatchResult {
	if len(items) == 0 {
		return nil
	}
	if workers <= 0 {
		workers = e.cfg.Workers
	}
	if workers > len(items) {
		workers = len(items)
	}

	results := make([]BatchResult, len(items))
	jobsCh := make(chan int, len(items))
	for i := range items {
		jobsCh <- i
	}
	close(jobsCh)

	var (
		wg     sync.WaitGroup
		doneMu sync.Mutex
		done   int
	)
	finished := func() {
		if onDone == nil {
			return
		}
		doneMu.Lock()
		done++
		onDone(done, len(items))
		doneMu.Unlock()
	}
	for i := 0; i < workers; i++ {
		wg.Add(1)
		safego.Go("watermark.batch.worker", func() {
			defer wg.Done()
			for idx := range jobsCh {
				if ctx.Err() != nil {
					results[idx] = BatchResult{
						ID:  items[idx].ID,
						Err: ctx.Err(),
					}
					continue
				}
				func() {
					defer finished()
					defer func() {
						if r := recover(); r != nil {
							results[idx] = BatchResult{
								ID:  items[idx].ID,
								Err: fmt.Errorf("panic processing item %s: %v", items[idx].ID, r),
							}
						}
					}()
					out, detected, format, info, score, gain, err := e.removeInternal(items[idx].Data)
					results[idx] = BatchResult{
						ID:           items[idx].ID,
						Output:       out,
						OutputFormat: format,
						Detected:     detected,
						Info:         info,
						Score:        score,
						Gain:         gain,
						Err:          err,
					}
				}()
			}
		})
	}
	wg.Wait()
	return results
}

// ProcessStream returns a stream channel receiving processed BatchResults from an input channel.
func (e *Engine) ProcessStream(ctx context.Context, in <-chan BatchItem, workers int) <-chan BatchResult {
	if workers <= 0 {
		workers = e.cfg.Workers
	}
	outCh := make(chan BatchResult, workers*2)
	var wg sync.WaitGroup

	for i := 0; i < workers; i++ {
		wg.Add(1)
		safego.Go("watermark.stream.worker", func() {
			defer wg.Done()
			for {
				select {
				case <-ctx.Done():
					return
				case item, ok := <-in:
					if !ok {
						return
					}
					var res BatchResult
					func() {
						defer func() {
							if r := recover(); r != nil {
								res = BatchResult{
									ID:  item.ID,
									Err: fmt.Errorf("panic processing item %s: %v", item.ID, r),
								}
							}
						}()
						out, detected, format, info, score, gain, err := e.removeInternal(item.Data)
						res = BatchResult{
							ID:           item.ID,
							Output:       out,
							OutputFormat: format,
							Detected:     detected,
							Info:         info,
							Score:        score,
							Gain:         gain,
							Err:          err,
						}
					}()
					select {
					case <-ctx.Done():
						return
					case outCh <- res:
					}
				}
			}
		})
	}

	safego.Go("watermark.stream.wait", func() {
		wg.Wait()
		close(outCh)
	})

	return outCh
}

// RemoveBatch processes multiple images concurrently using default settings.
func RemoveBatch(ctx context.Context, items []BatchItem, workers int) []BatchResult {
	return Default().ProcessBatch(ctx, items, workers)
}

// WriteAtomic writes image data to path atomically using fsutil.WriteAtomic.
// In-place overwrites preserve destination file integrity if write fails.
func WriteAtomic(path string, data []byte, perm os.FileMode) error {
	return fsutil.WriteAtomic(path, perm, func(w io.Writer) error {
		_, err := w.Write(data)
		return err
	})
}

// ProvenanceStore tracks output files generated by tasks to distinguish
// collisions from idempotent re-runs.
type ProvenanceStore struct {
	mu      sync.RWMutex
	records map[string]TaskParams
}

// NewProvenanceStore constructs a thread-safe ProvenanceStore.
func NewProvenanceStore() *ProvenanceStore {
	return &ProvenanceStore{
		records: make(map[string]TaskParams),
	}
}

// DefaultProvenance is the package-level shared provenance store.
var DefaultProvenance = NewProvenanceStore()

// Record associates outPath with the TaskParams that produced it.
func (s *ProvenanceStore) Record(outPath string, params TaskParams) {
	if s == nil || outPath == "" {
		return
	}
	clean := filepath.Clean(outPath)
	s.mu.Lock()
	defer s.mu.Unlock()
	s.records[clean] = params
}

// Get retrieves the TaskParams recorded for an output file.
func (s *ProvenanceStore) Get(outPath string) (TaskParams, bool) {
	if s == nil || outPath == "" {
		return TaskParams{}, false
	}
	clean := filepath.Clean(outPath)
	s.mu.RLock()
	defer s.mu.RUnlock()
	p, ok := s.records[clean]
	return p, ok
}

// IsIdempotent returns true if outPath exists on disk, has non-zero size,
// and was produced with identical task parameters (same input path + Corner + MinScore + MinGain + MaxGain).
func (s *ProvenanceStore) IsIdempotent(outPath string, params TaskParams) bool {
	fi, err := os.Stat(outPath)
	if err != nil || fi.Size() == 0 {
		return false
	}
	recorded, ok := s.Get(outPath)
	if !ok {
		return false
	}
	return recorded.Matches(params)
}

// Clear resets all stored records in the provenance store.
func (s *ProvenanceStore) Clear() {
	if s == nil {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	s.records = make(map[string]TaskParams)
}

// Matches checks if two TaskParams have identical input path and processing parameters.
func (p TaskParams) Matches(other TaskParams) bool {
	if p.InputPath == "" || other.InputPath == "" {
		return false
	}
	if filepath.Clean(p.InputPath) != filepath.Clean(other.InputPath) {
		return false
	}
	if p.Corner != other.Corner {
		return false
	}
	if math.Abs(p.MinScore-other.MinScore) > 1e-5 {
		return false
	}
	if math.Abs(p.MinGain-other.MinGain) > 1e-5 {
		return false
	}
	if math.Abs(p.MaxGain-other.MaxGain) > 1e-5 {
		return false
	}
	return true
}

// ResolveOutputPath determines the destination file path for an output item,
// applying collision avoidance (_nowm, _nowm_1, etc.) or recognizing an idempotent re-run.
// It returns (resolvedPath, isIdempotent).
func ResolveOutputPath(destDir, baseName, suffix, ext string, params TaskParams, store *ProvenanceStore) (string, bool) {
	if store == nil {
		store = DefaultProvenance
	}

	// First candidate
	candidate := filepath.Join(destDir, baseName+suffix+ext)
	fi, err := os.Stat(candidate)
	if err != nil {
		// File does not exist: ready to write
		return candidate, false
	}

	// Candidate exists: check if it's an idempotent re-run of the exact same task
	if fi.Size() > 0 && store.IsIdempotent(candidate, params) {
		return candidate, true
	}

	// Collision with a different task or source: generate numbered candidate _nowm_1, _nowm_2, ...
	for i := 1; ; i++ {
		var numberedSuffix string
		if suffix != "" {
			numberedSuffix = fmt.Sprintf("%s_%d", suffix, i)
		} else {
			numberedSuffix = fmt.Sprintf("_%d", i)
		}
		nextCandidate := filepath.Join(destDir, baseName+numberedSuffix+ext)
		nfi, nErr := os.Stat(nextCandidate)
		if nErr != nil {
			return nextCandidate, false
		}
		if nfi.Size() > 0 && store.IsIdempotent(nextCandidate, params) {
			return nextCandidate, true
		}
	}
}

// CopyFileAtomic copies source file data to destPath atomically via fsutil.WriteFileAtomic.
func CopyFileAtomic(srcPath, destPath string, perm os.FileMode) error {
	data, err := os.ReadFile(srcPath)
	if err != nil {
		return fmt.Errorf("read source file: %w", err)
	}
	if err := fsutil.WriteFileAtomic(destPath, data, perm); err != nil {
		return fmt.Errorf("write destination file: %w", err)
	}
	return nil
}
